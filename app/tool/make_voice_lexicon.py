#!/usr/bin/env python3
"""Builds lib/voice/voice_lexicon.dart: the phonemes (espeak-ng IPA, en-gb-x-rp, the way Piper
voices expect them) for every word the announcer can say. espeak-ng only runs here, at build
time; the app ships the phoneme strings, not espeak. Run after changing what the announcer says:

    sudo apt install espeak-ng && python3 tool/make_voice_lexicon.py
"""
import json, os, subprocess

WORDS = '''king queen rook bishop knight pawn takes to on and becomes castles side check checkmate
draw stalemate resigns wins white black game over the'''.split()
LETTERS = 'ABCDEFGH'
DIGITS = '12345678'


def ipa(text):
    out = subprocess.run(['espeak-ng', '-v', 'en-gb-x-rp', '-q', '--ipa', text], capture_output=True, text=True, check=True).stdout
    return ' '.join(out.split())


lex = {w: ipa(w) for w in WORDS}
lex['a'] = ipa('a queen').split(' ')[0]  # the article
# small words take their unstressed, in-sentence sound
lex['to'] = ipa('knight to').split(' ')[-1]
lex['on'] = ipa('takes pawn on').split(' ')[-1]
lex['and'] = ipa('pawn and').split(' ')[-1]
lex['the'] = ipa('the game').split(' ')[0]
for l in LETTERS:
    lex[l] = ipa(f'the letter {l}').split(' ')[-1]  # the letter's name
for d in DIGITS:
    lex[d] = ipa(d)

path = os.path.join(os.path.dirname(__file__), '..', 'lib', 'voice', 'voice_lexicon.dart')
with open(path, 'w') as f:
    f.write('// Generated by tool/make_voice_lexicon.py (espeak-ng IPA, en-gb-x-rp). Do not edit.\n')
    f.write('// Words are lower case, except single capital letters (square names).\n')
    f.write('const voiceLexicon = <String, String>{\n')
    for k, v in lex.items():
        f.write(f"  {json.dumps(k)}: {json.dumps(v, ensure_ascii=False)},\n")
    f.write('};\n')
print(json.dumps(lex, ensure_ascii=False, indent=0))
